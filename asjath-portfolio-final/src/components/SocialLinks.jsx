/**
 * @param {'footer' | 'contact' | 'default'} variant
 * @param {boolean} showEmpty - if true, show disabled placeholders for unset links
 */
export default function SocialLinks({ variant = 'default', showEmpty = false }) {
  const items = NETWORKS.map((n) => {
    const href = resolveSocialHref(n.key, socialLinks[n.key])
    return { ...n, href }
  }).filter((n) => n.href || showEmpty)

  if (items.length === 0) return null

  return (
    <div className={`social-block social-block--${variant}`}>
      {variant === 'contact' && (
        <div className="contact-social-label">Connect</div>
      )}
      <ul className={`social-links social-links--${variant}`} aria-label="Social links">
      {items.map((n) => {
        if (!n.href) {
          return (
            <li key={n.key}>
              <span
                className={`social-link social-link--${n.key} is-disabled`}
                title={`${n.label} — not configured yet`}
                aria-label={`${n.label} (not configured)`}
              >
                {n.icon}
              </span>
            </li>
          )
        }
        const external = !n.href.startsWith('mailto:')
        return (
          <li key={n.key}>
            <a
              className={`social-link social-link--${n.key}`}
              href={n.href}
              target={external ? '_blank' : undefined}
              rel={external ? 'noopener noreferrer' : undefined}
              aria-label={n.label}
              title={n.label}
            >
              {n.icon}
            </a>
          </li>
        )
      })}
    </ul>
    </div>
  )
}
